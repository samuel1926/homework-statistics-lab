const assert = require('node:assert/strict');
const { examples, calculate, chiSquareSurvival, parseDataset } = require('./stats');
const near = (actual, expected, eps = 1e-10) => assert.ok(Math.abs(actual - expected) < eps, `Expected ${expected}; received ${actual}`);
const strong = calculate(examples.dependent);
assert.equal(strong.n, 150);
assert.deepEqual(strong.rowTotals, [50, 50, 50]);
assert.deepEqual(strong.colTotals, [75, 75]);
assert.deepEqual(strong.observed, [[42,8],[24,26],[9,41]]);
assert.deepEqual(strong.expected, [[25,25],[25,25],[25,25]]);
near(strong.chi, 43.68);
assert.equal(strong.df, 2);
near(strong.p, Math.exp(-43.68 / 2));
near(strong.v, Math.sqrt(43.68 / 150));
const nullExample = calculate(examples.independent);
assert.equal(nullExample.chi, 0);
assert.equal(nullExample.p, 1);
const weak = calculate(examples.weak);
near(weak.chi, 2.56);
near(weak.p, Math.exp(-1.28));
near(chiSquareSurvival(3.841458820694124, 1), 0.05, 1e-10);
near(chiSquareSurvival(5.991464547107979, 2), 0.05, 1e-10);
near(chiSquareSurvival(7.814727903251179, 3), 0.05, 1e-10);
const raw = calculate('X,F\nA,Yes\nA,No\nA,Yes\nB,No');
assert.equal(raw.n, 4);
assert.deepEqual(raw.observed, [[2,1],[0,1]]);
const semi = calculate('X;F;count\n"New; York";Yes;2\n"New; York";No;2\nRome;Yes;1\nRome;No;3');
assert.deepEqual(semi.rowTotals, [4,4]);
assert.deepEqual(semi.colTotals, [3,5]);
assert.equal(semi.xLabels[0], 'New; York');
const quoted = parseDataset('"A,B","C""D"\n"E",F', false);
assert.deepEqual(quoted.records[0], { x: 'A,B', f: 'C"D', count: 1 });
const singleCategory = calculate('X,F\nA,Yes\nA,No');
assert.equal(singleCategory.df, 0);
assert.equal(singleCategory.p, null);
assert.equal(singleCategory.v, null);
const sparse = calculate('X,F,count\nA,Yes,1\nB,No,1');
assert.equal(sparse.unreliable, true);
assert.throws(() => calculate('X,F,count\nA,B,-1'), /invalid count/);
assert.throws(() => calculate('X,F,count\nA,B,nope'), /invalid count/);
assert.throws(() => calculate('X,F\nA,B\nC'), /needs 2 fields/);
assert.throws(() => calculate('X,F\n"A,B'), /no matching closing quote/);
console.log('Lesson 06 statistics tests: all passed.');
